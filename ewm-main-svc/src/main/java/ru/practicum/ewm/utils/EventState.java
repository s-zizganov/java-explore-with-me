package ru.practicum.ewm.utils;

/**
 * Перечисление состояний события.
 * Используется для обозначения текущего статуса события в системе.
 */
public enum EventState {
    /**
     * Событие ожидает публикации (черновик, на модерации).
     */
    PENDING,
    /**
     * Событие опубликовано и доступно для пользователей.
     */
    PUBLISHED,
    /**
     * Событие отменено.
     */
    CANCELED
}
